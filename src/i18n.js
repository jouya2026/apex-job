let current = 'fa';
try { current = localStorage.getItem('aj.lang') || 'fa'; } catch {}
if (!S[current]) current = 'fa';

export const getLang = () => current;
export const getDir = () => (LANGS.find((l) => l.code === current) || LANGS[0]).dir;

export function setLang(code) {
  if (!S[code]) return;
  current = code;
  try { localStorage.setItem('aj.lang', code); } catch {}
  applyDocumentLang();
}

export function applyDocumentLang() {
  document.documentElement.lang = current === 'fa' ? 'fa-AF' : current === 'ps' ? 'ps-AF' : 'en';
  document.documentElement.dir = getDir();
}

const FA_DIGITS = '۰۱۲۳۴۵۶۷۸۹';
export function num(n) {
  const s = String(n);
  return current === 'en' ? s : s.replace(/\d/g, (d) => FA_DIGITS[d]);
}

export function t(key, vars = {}) {
  let s = (S[current] && S[current][key]) ?? S.en[key] ?? key;
  for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(k === 'n' ? num(v) : v);
  return s;
}

function fromMap(map, value) {
  if (!value) return '';
  if (current === 'en') return value;
  const hit = map[value];
  return hit ? hit[current] : value;
}
export const trProvince = (v) => fromMap(PROVINCES, v);
export const trCategory = (v) => fromMap(CATEGORIES, v);
export const trType = (v) => fromMap(JOB_TYPES, v);
export const trGender = (v) => fromMap(GENDERS, v);
export const trNationality = (v) => fromMap(NATIONALITIES, v);

/** تاریخ: برای دری و پښتو با تقویم هجری شمسی (حمل، ثور…) */
export function fmtDate(iso) {
  if (!iso) return '';
  const d = new Date(iso.length === 10 ? iso + 'T12:00:00' : iso);
  if (isNaN(d)) return iso;
  try {
    if (current === 'en') return new Intl.DateTimeFormat('en-GB', { day: 'numeric', month: 'short', year: 'numeric' }).format(d);
    return new Intl.DateTimeFormat(`${current}-AF-u-ca-persian-nu-arabext`, { day: 'numeric', month: 'long', year: 'numeric' }).format(d);
  } catch {
    return num(iso.slice(0, 10));
  }
}

export function timeAgo(iso) {
  if (!iso) return '';
  const diff = (Date.now() - new Date(iso).getTime()) / 1000;
  if (diff < 90) return t('justNow');
  if (diff < 3600) return t('minAgo', { n: Math.round(diff / 60) });
  if (diff < 86400) return t('hourAgo', { n: Math.round(diff / 3600) });
  return t('dayAgo', { n: Math.round(diff / 86400) });
}
